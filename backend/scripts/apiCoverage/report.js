/**
 * The API coverage report: docs/api-coverage/README.md (gap list per shop, then the full catalog)
 * and docs/api-coverage/report-data.json (the same rows, for the report web page).
 * usage: npm run api-coverage   (rebuilds the gap notes first, then writes both files)
 */
const fs = require('fs')
const path = require('path')
const { shopCoverage, appOf, readJson, DOCS } = require('./compare')

const SHOPS = [
  { key: 'ebay', label: 'eBay' },
  { key: 'tiktok_shop', label: 'TikTok Shop' },
  { key: 'temu', label: 'Temu' },
]
const STATUSES = ['covered', 'covered-older', 'missing', 'not-for-sellers']
const RANK = { high: 0, medium: 1, low: 2, small: 0, large: 2 }

/** Coverage rows of every shop, each missing row carrying its gap note. */
function reportData() {
  return SHOPS.map(({ key, label }) => {
    const catalog = readJson('catalog', `${key}.json`)
    const gaps = readJson('gaps', `${key}.json`)
    const rows = shopCoverage(key).map((r) => (gaps[r.id] ? { ...r, gap: gaps[r.id] } : r))
    const app = appOf(key)
    return { key, label, sources: catalog.sources, researchedAt: catalog.researchedAt, notes: catalog.notes || [], ...(app ? { app } : {}), rows }
  })
}

const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim()
const code = (s) => `\`${s}\``
const scopeCell = (r) => cell(String(r.scope || '').replace(/https:\/\/api\.ebay\.com\/oauth\/api_scope\/?/g, '').replace(/^$/, 'basic (api_scope)')) || '—'
const accessCell = (r) => (r.access === 'needs-scope' ? `needs scope: ${cell(r.scope)}` : r.access === 'granted' ? 'available now' : '—')
const ACCESS = { granted: 0, undefined: 0, 'needs-scope': 1 }
const byRank = (a, b) => ACCESS[a.access] - ACCESS[b.access] || RANK[a.gap.priority] - RANK[b.gap.priority] || RANK[a.gap.size] - RANK[b.gap.size] || a.id.localeCompare(b.id)

function buildReport(data = reportData()) {
  const out = []
  const line = (s = '') => out.push(s)
  line('# Shop API coverage')
  line()
  line("Every official seller API endpoint of eBay, TikTok Shop and Temu, checked against the calls the dashboard's code makes (`backend/marketplaces/<shop>/`). Generated by `npm run api-coverage` (backend) from `catalog/` and `gaps/`; do not edit by hand.")
  line()
  line("Access (shops with a recorded app): **available now** — the shop's app already holds the scope; **needs scope** — the app must be granted that scope first. Within each section, gaps available now come first.")
  line()
  line('Statuses: **covered** — called; **covered (older version)** — called at an older API version; **missing** — a seller endpoint not called yet (each has a gap note); **not for sellers** — buyer, creator or partner APIs, never a gap.')
  line()
  line('| Shop | Endpoints | Covered | Older version | Missing | Not for sellers | High-priority gaps | Gaps available now |')
  line('|---|---:|---:|---:|---:|---:|---:|---:|')
  for (const s of data) {
    const n = (st) => s.rows.filter((r) => r.status === st).length
    line(`| ${s.label} | ${s.rows.length} | ${n('covered')} | ${n('covered-older')} | ${n('missing')} | ${n('not-for-sellers')} | ${s.rows.filter((r) => r.gap?.priority === 'high').length} | ${s.app ? s.rows.filter((r) => r.status === 'missing' && r.access === 'granted').length : '—'} |`)
  }
  for (const s of data) {
    line()
    line(`## ${s.label}`)
    line()
    line(`Researched ${s.researchedAt}. Sources: ${s.sources.map((u) => `<${u}>`).join(', ')}.`)
    for (const note of s.notes) line(`- ${note}`)
    if (s.app) {
      line()
      line(`App category: ${s.app.appCategory}. Scopes the app holds (${s.app.scopes.length}): ${s.app.scopes.join(', ')}.`)
      line()
      line(s.app.source)
    }
    line()
    line(`### ${s.label} — gaps by section`)
    const missing = s.rows.filter((r) => r.status === 'missing')
    const sections = [...new Set(missing.map((r) => r.gap.section))].sort((a, b) => a.startsWith('new: ') - b.startsWith('new: ') || a.localeCompare(b))
    for (const section of sections) {
      const rows = missing.filter((r) => r.gap.section === section).sort(byRank)
      line()
      line(`#### ${section} (${rows.length})`)
      line()
      line('| Access | Priority | Size | Endpoint | Scope | Name | What it gives the seller |')
      line('|---|---|---|---|---|---|---|')
      for (const r of rows) line(`| ${accessCell(r)} | ${r.gap.priority} | ${r.gap.size} | ${code(r.id)}${r.confirmed ? '' : ' (confirm in partner account)'} | ${r.scope ? scopeCell(r) : '—'} | ${cell(r.name)} | ${cell(r.gap.value)} |`)
    }
    line()
    line(`### ${s.label} — full catalog`)
    line()
    line('<details><summary>All endpoints</summary>')
    line()
    line('| Status | Group | Endpoint | Name | Summary | Called from |')
    line('|---|---|---|---|---|---|')
    const ordered = [...s.rows].sort((a, b) => a.group.localeCompare(b.group) || STATUSES.indexOf(a.status) - STATUSES.indexOf(b.status) || a.id.localeCompare(b.id))
    for (const r of ordered) {
      const status = r.status === 'covered-older' ? `covered (older version: ${code(r.calledAs)})` : r.status.replace(/-/g, ' ')
      line(`| ${status} | ${cell(r.group)} | ${code(r.id)} | ${cell(r.name)} | ${cell(r.summary)} | ${r.files.map(code).join(', ')} |`)
    }
    line()
    line('</details>')
  }
  return `${out.join('\n')}\n`
}

module.exports = { reportData, buildReport }

if (require.main === module) {
  const { gapNotes } = require('./build-gaps')
  for (const { key } of SHOPS) fs.writeFileSync(path.join(DOCS, 'gaps', `${key}.json`), `${JSON.stringify(gapNotes(key), null, 2)}\n`)
  const data = reportData()
  fs.writeFileSync(path.join(DOCS, 'README.md'), buildReport(data))
  fs.writeFileSync(path.join(DOCS, 'report-data.json'), `${JSON.stringify(data)}\n`)
  console.log('wrote docs/api-coverage/README.md and report-data.json')
}
